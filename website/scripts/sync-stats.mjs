import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");

const read = (path) => readFile(join(repo, path), "utf8");
const countMatches = (source, pattern) => [...source.matchAll(pattern)].length;

const packageJson = JSON.parse(await read("package.json"));
const library = await read("lib/main.tsp");
const diagnosticsSource = await read("src/lib.ts");
const protocolsSource = await read("src/constants/protocols.ts");
const bindingsSource = await read("src/constants/generated-bindings.ts");

const protocolBlock = protocolsSource.match(/const PROTOCOLS = \[([\s\S]*?)\] as const;/u);
const bindingsBlock = bindingsSource.match(
  /export const GENERATED_LATEST_VERSIONS: Record<string, string> = \{([\s\S]*?)\};/u,
);

if (!protocolBlock || !bindingsBlock) {
  throw new Error("Could not locate protocol or binding registries");
}

const examples = (await readdir(join(repo, "examples"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .length;

const stats = {
  version: packageJson.version,
  decorators: countMatches(library, /^extern dec /gmu),
  protocols: countMatches(protocolBlock[1], /^\s+"[a-z0-9]+",?$/gmu),
  bindings: countMatches(bindingsBlock[1], /^\s+"[a-z0-9]+":/gmu),
  diagnostics: countMatches(diagnosticsSource, /^ {4}"[A-Za-z0-9-]+": \{/gmu),
  examples,
};

const output = `// AUTO-GENERATED by scripts/sync-stats.mjs — do not edit by hand.
// Source of truth: package.json, lib/main.tsp, src/lib.ts, src/constants/.
export const stats = ${JSON.stringify(stats, null, 2)} as const;

export type Stats = typeof stats;
`;

await writeFile(join(here, "..", "src", "data", "stats.ts"), output);
console.log(
  `stats: v${stats.version} · ${stats.decorators} decorators · ${stats.protocols} protocols · ${stats.bindings} bindings · ${stats.diagnostics} diagnostics · ${stats.examples} examples`,
);
