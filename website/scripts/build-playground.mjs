/**
 * Builds the in-browser playground engine.
 *
 *   node scripts/build-playground.mjs
 *
 * Two outputs:
 *   1. playground/generated-assets.ts — the TypeSpec stdlib and our library
 *      entrypoint inlined as strings, so the browser needs no filesystem.
 *   2. public/playground/engine.js — the real compiler + real emitter,
 *      bundled as a lazy-loaded ES module.
 *
 * Both are generated. Never edit them by hand.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const website = join(here, "..");
const repo = join(website, "..");

const compilerDir = join(repo, "node_modules", "@typespec", "compiler");
const compilerLib = join(compilerDir, "lib");

const literal = (value) => JSON.stringify(value);

async function collectTypeSpecFiles(directory, virtualPrefix) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(
        ...(await collectTypeSpecFiles(
          absolute,
          `${virtualPrefix}/${entry.name}`,
        )),
      );
      continue;
    }
    if (!entry.name.endsWith(".tsp")) continue;
    files.push([
      `${virtualPrefix}/${entry.name}`,
      await readFile(absolute, "utf8"),
    ]);
  }
  return files;
}

const stdlibEntries = await collectTypeSpecFiles(
  compilerLib,
  "./node_modules/@typespec/compiler/lib",
);

const stdlib = Object.fromEntries(stdlibEntries);

const emitterManifest = JSON.parse(
  await readFile(join(repo, "package.json"), "utf8"),
);
const emitterPackageJson = JSON.stringify({
  name: emitterManifest.name,
  version: emitterManifest.version,
  type: "module",
  main: "dist/src/index.js",
  exports: {
    ".": {
      typespec: "./lib/main.tsp",
      default: "./dist/src/index.js",
    },
  },
  tspMain: "lib/main.tsp",
});

const compilerPackageJson = JSON.stringify({
  name: "@typespec/compiler",
  version: JSON.parse(await readFile(join(compilerDir, "package.json"), "utf8"))
    .version,
  type: "module",
  main: "dist/src/index.js",
});

const emitterMainTsp = await readFile(join(repo, "lib", "main.tsp"), "utf8");

const generated = `// AUTO-GENERATED by website/scripts/build-playground.mjs — do not edit.
// Source of truth: node_modules/@typespec/compiler/lib, lib/main.tsp, package.json.
export const compilerStdlib: Record<string, string> = ${literal(stdlib)};

export const compilerPackageJson: string = ${literal(compilerPackageJson)};

export const emitterPackageJson: string = ${literal(emitterPackageJson)};

export const emitterMainTsp: string = ${literal(emitterMainTsp)};
`;

await writeFile(
  join(website, "playground", "generated-assets.ts"),
  generated,
  "utf8",
);

const outDir = join(website, "public", "playground");
await mkdir(outDir, { recursive: true });

const result = await build({
  absWorkingDir: website,
  entryPoints: [join(website, "playground", "engine.ts")],
  outfile: join(outDir, "engine.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none",
  metafile: true,
  external: ["@typespec/http"],
  banner: {
    js: 'globalThis.process??={env:{},platform:"linux",argv:[],cwd:()=>"/",versions:{},emitWarning(){}};',
  },
});

const bytes = Object.values(result.metafile.outputs).reduce(
  (total, output) => total + output.bytes,
  0,
);

console.log(
  `playground engine: ${(bytes / 1024 / 1024).toFixed(2)} MB · ${stdlibEntries.length} stdlib files inlined`,
);
